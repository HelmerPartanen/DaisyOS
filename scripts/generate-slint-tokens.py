#!/usr/bin/env python3
"""Translate existing DaisyTheme resources; XAML remains the migration authority."""
import argparse,hashlib,json,re,xml.etree.ElementTree as E
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];SOURCE=ROOT/'src/DaisyOS.Shell/Themes/DaisyTheme.axaml';KEY='{http://schemas.microsoft.com/winfx/2006/xaml}Key'
def kebab(s):
    split=lambda m:m[1]+'-'+m[2]
    return re.sub(r'([a-z0-9])([A-Z])',split,re.sub(r'(.)([A-Z][a-z]+)',split,s)).lower()
def rgba(s,opacity=1):
    s=s.strip().lstrip('#')
    if len(s)==6:s='FF'+s
    if len(s)!=8:raise ValueError(s)
    return '#'+s[2:]+f'{round(int(s[:2],16)*opacity):02X}'
def generate():
    root=E.parse(SOURCE).getroot();shared={e.get(KEY):e for e in root if e.get(KEY)}
    dictionaries={e.get(KEY):dict(shared,**{c.get(KEY):c for c in e if c.get(KEY)}) for e in root.iter() if e.tag.endswith('ResourceDictionary') and e.get(KEY) in ['Light','Dark']}
    def resolve(key,theme,seen=()):
        if key in seen:raise ValueError(key)
        e=dictionaries[theme][key];s=(e.text or '').strip() if e.tag.endswith('Color') else e.get('Color','')
        if s.startswith('{'):s=resolve(s.split()[1].rstrip('}'),theme,seen+(key,))
        if not s.startswith('#'):raise ValueError(key)
        return s
    roles=['SurfaceCanvas','SurfaceBase','SurfaceBaseSolid','SurfaceRaised','SurfaceCard','SurfaceGlassSolid','SurfaceSunken','SurfaceInput','SurfaceInputHover','ContentPrimary','ContentSecondary','ContentTertiary','ContentDisabled','StrokeSubtle','StrokeDefault','StrokeStrong','StateHover','StatePressed','StateSelected','OverlayScrim','ActionPrimary','ActionPrimaryHover','ActionPrimaryPressed','ActionPrimarySubtle','ActionSecondary','ActionSecondaryHover','ActionSecondaryPressed','ContentOnAction','ContentOnPrimaryAction','FocusRing','ToggleTrackOff','ToggleThumb','ToggleThumbStroke','StatusSuccess','StatusWarning','StatusDanger','StatusInfo']
    palettes={t:{} for t in dictionaries}
    for t in dictionaries:
        for role in roles:
            key=role+'Brush';e=dictionaries[t][key];palettes[t][role]=rgba(resolve(key,t),float(e.get('Opacity','1')))
    rows=['// GENERATED by scripts/generate-slint-tokens.py from DaisyTheme.axaml.','export global DaisyTheme {','    in-out property<bool> dark: true;','    in-out property<bool> reduce-motion: false;','    in-out property<bool> high-contrast: false;','    in-out property<float> text-scale: 1;','    in-out property<string> font-family: "Atkinson Hyperlegible";']
    dynamic={'ActionPrimary','ActionPrimaryHover','ActionPrimaryPressed','ContentOnAction','FocusRing'}
    for role in roles:
        expression=f'self.dark ? {palettes["Dark"][role]} : {palettes["Light"][role]}'
        # App.axaml.cs ApplyAccessibilityPreference overrides these roles.
        high={'SurfaceBase':('#000000FF','#FFFFFFFF'),'SurfaceRaised':('#000000FF','#FFFFFFFF'),'SurfaceSunken':('#1F1F1FFF','#E6E6E6FF'),'SurfaceInput':('#242424FF','#FFFFFFFF'),'SurfaceInputHover':('#2C2C2CFF','#F4F4F4FF')}
        if role.startswith('Content') and role not in ['ContentOnAction','ContentOnPrimaryAction'] or role in ['StrokeDefault','StrokeStrong']: high[role]=('#FFFFFFFF','#000000FF')
        if role in high: expression=f'self.high-contrast ? (self.dark ? {high[role][0]} : {high[role][1]}) : ({expression})'
        rows.append(f'    {"in-out" if role in dynamic else "out"} property<color> {kebab(role)}: {expression};')
    geometry={}
    for key,e in shared.items():
        value=(e.text or '').strip();kind=e.tag.split('}')[-1]
        if kind in ['Double','CornerRadius'] and ',' not in value and key.startswith(('Space','Radius','Rounded','TypeSize','TypeLine','ButtonHeight','ControlHeight','InputHeight','HitTarget','Toggle','IconSize')):
            if not re.fullmatch(r'[0-9.]+',value):continue
            suffix=' * self.text-scale' if key.startswith(('TypeSize','TypeLine')) else ''
            rows.append(f'    out property<length> {kebab(key)}: {value}px{suffix};');geometry[key]=value
        if kind=='TimeSpan' and key.startswith('Motion'):
            h,m,s=map(float,value.split(':'));ms=round((h*3600+m*60+s)*1000)
            rows.append(f'    out property<duration> {kebab(key)}: self.reduce-motion ? 0ms : {ms}ms;');geometry[key]=value
    accents={theme:[rgba(resolve('AccentOption'+name+'Color',theme)) for name in ['Default','Purple','Pink','Red','Orange','Green','Gray','White','Default']] for theme in dictionaries}
    rows+=['}'];return '\n'.join(rows)+'\n',json.dumps({'source':str(SOURCE.relative_to(ROOT)),'sourceSha256':hashlib.sha256(SOURCE.read_bytes()).hexdigest(),'palettes':palettes,'accents':accents,'geometry':geometry},indent=2)+'\n'
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    for path,value in zip([ROOT/'crates/daisy-ui/themes/tokens.slint',ROOT/'crates/daisy-ui/themes/source-tokens.json'],generate()):
        if a.check:
            if not path.exists() or path.read_text()!=value:raise SystemExit('Token drift: '+str(path))
        else:path.write_text(value)
